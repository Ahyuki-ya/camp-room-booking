-- =====================================================================
-- 部屋の入れ替え（5部屋 -> 7部屋）/ 要件定義書 v2 §11.2
--
-- 04_seed.sql は「まっさらな DB を作る」ためのもので、既に稼働している
-- プロジェクトには流せない（rooms の id が衝突する）。稼働中の DB に
-- 同じ状態を作るのがこのファイル。何度流しても結果は同じ。
--
-- 部屋名は表示専用で、reservations は room_id を参照している。したがって
-- 既存の予約は id が同じ限り影響を受けない。ただし今回は id 1〜5 の指す
-- 部屋そのものが変わる（例: id 3 は D3 から D2 になる）ため、予約が入って
-- いる状態で流すと、その予約は別の部屋に付け替わったことになる。
-- 2026-09-01 時点で reservations は 0 件であることを確認して実行した。
-- =====================================================================

insert into rooms (id, name, sort_order) values
  (1, 'B2大', 1),
  (2, 'D1中', 2),
  (3, 'D2中', 3),
  (4, 'D3中', 4),
  (5, 'E1中', 5),
  (6, 'E2中', 6),
  (7, 'E3中', 7)
on conflict (id) do update
  set name = excluded.name, sort_order = excluded.sort_order;

-- 上の7件以外は残さない。参照している予約があれば FK で失敗するので、
-- 「使われていない部屋だけが消える」ことは DB が保証する。
delete from rooms where id > 7;
